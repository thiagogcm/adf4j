package dev.nthings.adf4j.ast;

/// A block-level ADF node. An unrecognized `type` parses as {@link UnknownBlock}, keeping its raw
/// JSON. The permits list grows with ADF (see {@link AdfNode}). {@link BlockCard} and
/// {@link EmbedCard} are also {@link AdfInline}, since they occur inside paragraphs.
public sealed interface AdfBlock extends AdfNode
    permits Paragraph,
        Heading,
        Blockquote,
        CodeBlock,
        Panel,
        Rule,
        BulletList,
        OrderedList,
        ListItem,
        TaskList,
        TaskItem,
        BlockTaskItem,
        DecisionList,
        DecisionItem,
        Table,
        TableRow,
        TableCell,
        MediaSingle,
        MediaGroup,
        Media,
        Caption,
        Expand,
        NestedExpand,
        LayoutSection,
        LayoutColumn,
        Extension,
        BodiedExtension,
        MultiBodiedExtension,
        ExtensionFrame,
        SyncBlock,
        BodiedSyncBlock,
        BlockCard,
        EmbedCard,
        UnknownBlock,
        BlockTaskItemContent,
        BlockquoteContent,
        BodiedExtensionContent,
        BodiedSyncBlockContent,
        DocContent,
        ExpandContent,
        LayoutColumnContent,
        ListItemContent,
        NestedExpandContent,
        PanelContent,
        TableCellContent,
        TaskListContent {}
