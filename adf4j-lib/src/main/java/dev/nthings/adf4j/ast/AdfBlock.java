package dev.nthings.adf4j.ast;

/// A block-level ADF node. A `type` the parser does not recognize parses as {@link UnknownBlock}
/// with its raw JSON preserved. The permits list grows with ADF (see the {@link AdfNode} note).
/// {@link BlockCard} and {@link EmbedCard} are also {@link AdfInline}, because they occur inside
/// paragraphs too.
public sealed interface AdfBlock extends AdfNode
    permits Paragraph,
        Heading,
        Blockquote,
        CodeBlock,
        Panel,
        Rule,
        BulletList,
        OrderedList,
        ListItem,
        TaskList,
        TaskItem,
        BlockTaskItem,
        DecisionList,
        DecisionItem,
        Table,
        TableRow,
        TableCell,
        MediaSingle,
        MediaGroup,
        Media,
        Caption,
        Expand,
        NestedExpand,
        LayoutSection,
        LayoutColumn,
        Extension,
        BodiedExtension,
        MultiBodiedExtension,
        ExtensionFrame,
        SyncBlock,
        BodiedSyncBlock,
        BlockCard,
        EmbedCard,
        UnknownBlock,
        BlockTaskItemContent,
        BlockquoteContent,
        BodiedExtensionContent,
        BodiedSyncBlockContent,
        DocContent,
        ExpandContent,
        LayoutColumnContent,
        ListItemContent,
        NestedExpandContent,
        PanelContent,
        TableCellContent,
        TaskListContent {}
